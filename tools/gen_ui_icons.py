#!/usr/bin/env python3
"""Generate src/ui_icons.h: the interface icons (menu actions, toolbar) built into the app, so they look the same
everywhere (no icon font needed). Every third_party/lucide-icons/*.svg (Lucide, ISC) is embedded: to add one, copy
its SVG there from https://lucide.dev and run this again. Strokes are white; the app tints them when drawing."""
import os, re
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(root, "third_party", "lucide-icons")
OUT = os.path.join(root, "src", "ui_icons.h")

names = sorted(f[:-4] for f in os.listdir(SRC) if f.endswith(".svg"))
out = ["// Generated by tools/gen_ui_icons.py from third_party/lucide-icons/ (Lucide, ISC licence). Do not edit.",
       "enum {"]
out += ["    UI_%s," % re.sub(r"[^A-Z0-9]", "_", n.upper()) for n in names]
out += ["    UI_ICON_COUNT", "};", "static const char *const g_ui_icons[UI_ICON_COUNT] = {"]
for n in names:
    svg = open(os.path.join(SRC, n + ".svg"), encoding="ascii").read()
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r"\s+", " ", svg).replace("> <", "><").replace(" />", "/>").strip()
    svg = svg.replace("currentColor", "#FFFFFF")
    # Lucide draws dots (the i of "info", list bullets) as a 0.01 long stroke with round caps; nanosvg leaves out such
    # a short stroke, so they become filled circles of the stroke's width
    svg = re.sub(r'<path d="M([\d.]+) ([\d.]+)[hv]\.01"/>', r'<circle cx="\1" cy="\2" r="1" fill="#FFFFFF" stroke="none"/>', svg)
    out.append('    "%s",' % svg.replace("\\", "\\\\").replace('"', '\\"'))
out.append("};")
open(OUT, "w").write("\n".join(out) + "\n")
print("wrote %s (%d icons)" % (OUT, len(names)))
