#!/usr/bin/env python3
"""Embed the icon themes into src/icons_data.h (ASCII C strings).

Canonical icon names are the Material Icon Theme file names; other themes map onto them
via tools/icon_aliases.py and fall back to their generic file icon.
Themes: Material, Catppuccin (mocha), Symbols, Monokai (Symbols shapes, Monokai palette)."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..")
sys.path.insert(0, here)
from icon_aliases import (CATPPUCCIN, SYMBOLS, MONOKAI, MONOKAI_CATEGORY, FOLDERS, catppuccin_folder, symbols_folder,
                          canonical_names)

def load(path):
    svg = open(path, encoding="utf-8").read()
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r"<\?xml.*?\?>", "", svg, flags=re.S)
    svg = re.sub(r"\s+", " ", svg).strip()
    svg.encode("ascii")  # must be ASCII
    return svg

def recolor(svg, color):
    # every explicit fill/stroke colour becomes the category colour ("none" stays)
    svg = re.sub(r'(fill|stroke)="#[0-9A-Fa-f]{3,8}"', lambda m: f'{m.group(1)}="{color}"', svg)
    svg = re.sub(r'(fill|stroke):\s*#[0-9A-Fa-f]{3,8}', lambda m: f'{m.group(1)}:{color}', svg)
    return svg

canon = canonical_names(root)
cat_of = {n: c for c, names in MONOKAI_CATEGORY.items() for n in names}

themes = []  # (name, [svg per canonical name])
mat_dir = os.path.join(root, "third_party", "material-icons")
themes.append(("Material", [load(os.path.join(mat_dir, n + ".svg")) for n in canon]))

def is_folder(n): return n == "folder" or n.startswith("folder-")

def mapped(dirname, aliases, default, folder_alias, folder_default):
    d = os.path.join(root, "third_party", dirname)
    out = []
    for n in canon:
        alias, dflt = (folder_alias(n), folder_default) if is_folder(n) else (aliases.get(n, n), default)
        f = os.path.join(d, alias + ".svg")
        if not os.path.exists(f): f = os.path.join(d, dflt + ".svg")
        out.append(load(f))
    return out

themes.append(("Catppuccin", mapped("icons-catppuccin", CATPPUCCIN, "_file", catppuccin_folder, "_folder")))
sym = mapped("icons-symbols", SYMBOLS, "document", symbols_folder, "folder")

def monokai_folder(svg):  # Symbols folders: slate outline -> yellow, the emblem -> orange
    svg = re.sub(r'#64748[Bb]', "#FFD866", svg)
    return re.sub(r'(fill|stroke)="#(?!FFD866)[0-9A-Fa-f]{3,8}"', lambda m: f'{m.group(1)}="{MONOKAI["orange"]}"', svg)
themes.append(("Symbols", sym))
def monokai_trash(svg):  # keeps the theme-dependent colours (#FEFEFE / #FDFDFD), anything else -> pink
    return re.sub(r'(fill|stroke)="#(?!FEFEFE|FDFDFD)[0-9A-Fa-f]{3,8}"', lambda m: f'{m.group(1)}="{MONOKAI["pink"]}"', svg)

# #FEFEFE marks an icon's main colour that follows the UI theme (light grey on dark themes, dark grey on
# light ones), #FDFDFD a darker shade of it (details on a filled shape); icons.c substitutes them when parsing.
themes.append(("Monokai", [monokai_folder(s) if is_folder(n) else monokai_trash(s) if n == "trash"
                           else recolor(s, MONOKAI[cat_of.get(n, "gray")]) for n, s in zip(canon, sym)]))

# de-duplicate identical SVG strings across all themes
pool, ids = {}, []
lines = ["// Generated by tools/gen_icons.py -- do not edit.",
         "// Icons: Material Icon Theme, Catppuccin, Symbols (all MIT); Monokai = Symbols recoloured.", ""]
for tname, svgs in themes:
    row = []
    for s in svgs:
        if s not in pool:
            pool[s] = f"ICN_{len(pool)}"
            esc = s.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'static const char {pool[s]}[] = "{esc}";')
        row.append(pool[s])
    ids.append((tname, row))
lines.append("")
lines.append(f"#define ICON_COUNT {len(canon)}")
lines.append(f"#define ICON_THEMES {len(themes)}")
lines.append("static const char *const g_icon_names[ICON_COUNT] = {" + ", ".join(f'"{n}"' for n in canon) + "};")
lines.append("static const char *const g_icon_theme_names[ICON_THEMES] = {" + ", ".join(f'"{t}"' for t, _ in themes) + "};")
folder_map = sorted((name, icon) for icon, names in FOLDERS.items() for name in names)
lines.append("// Folder names (lowercase, without leading '.' / '_') with their own folder icon, sorted.")
lines.append("typedef struct { const char *name, *icon; } FolderIconName;")
lines.append(f"static const FolderIconName g_folder_icon_names[{len(folder_map)}] = {{")
for i in range(0, len(folder_map), 6):
    lines.append("    " + " ".join(f'{{"{a}", "{b}"}},' for a, b in folder_map[i:i + 6]))
lines.append("};")
lines.append("static const char *const g_icon_svg[ICON_THEMES][ICON_COUNT] = {")
for tname, row in ids:
    lines.append("    {" + ", ".join(row) + "},")
lines.append("};")
out = os.path.join(root, "src", "icons_data.h")
open(out, "w", encoding="ascii").write("\n".join(lines) + "\n")
print(f"wrote {out}: {len(canon)} icons x {len(themes)} themes, {len(pool)} unique SVGs, {os.path.getsize(out)} bytes")
