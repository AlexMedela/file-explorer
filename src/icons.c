// Icons may mark their main colour #FEFEFE (and #FDFDFD for a shade of it): it follows the UI theme (secondary
// text colour), so they stay visible on light and dark themes alike (the trash bin).
#define ICON_THEME_MARK "#FEFEFE"
#define ICON_THEME_SHADE "#FDFDFD" // the same colour, mixed halfway towards the background
static u32 g_icon_main = 0xFFFFFFFF, g_icon_bg; // colours behind the marks (re-rasterized when they change)

// The logo follows the accent colour: its colours are hue-rotated from the default blue accent to the current
// one (saturation scaled the same way, lightness kept), so the design is unchanged and Blue looks exactly as drawn.
static void rgb_to_hsl(u32 c, f32 *h, f32 *s, f32 *l) {
    f32 r = ((c >> 16) & 255) / 255.f, g = ((c >> 8) & 255) / 255.f, b = (c & 255) / 255.f;
    f32 mx = MAX(r, MAX(g, b)), mn = MIN(r, MIN(g, b)), d = mx - mn;
    *l = (mx + mn) * 0.5f;
    *s = d < 1e-6f ? 0 : d / (1 - fabsf(2 * *l - 1));
    if (d < 1e-6f) *h = 0;
    else if (mx == r) *h = fmodf((g - b) / d + 6, 6) / 6;
    else if (mx == g) *h = ((b - r) / d + 2) / 6;
    else *h = ((r - g) / d + 4) / 6;
}

static u32 hsl_to_rgb(f32 h, f32 s, f32 l) {
    h = fmodf(h + 1, 1);
    f32 c = (1 - fabsf(2 * l - 1)) * s, x = c * (1 - fabsf(fmodf(h * 6, 2) - 1)), m = l - c / 2, r, g, b;
    int k = (int)(h * 6) % 6;
    r = k == 0 || k == 5 ? c : k == 1 || k == 4 ? x : 0;
    g = k == 1 || k == 2 ? c : k == 0 || k == 3 ? x : 0;
    b = k == 3 || k == 4 ? c : k == 2 || k == 5 ? x : 0;
    u32 R8 = (u32)CLAMP((r + m) * 255 + 0.5f, 0, 255), G8 = (u32)CLAMP((g + m) * 255 + 0.5f, 0, 255), B8 = (u32)CLAMP((b + m) * 255 + 0.5f, 0, 255);
    return R8 << 16 | G8 << 8 | B8;
}

#define LOGO_BASE_ACCENT 0x4C9BFF // the accent the artwork is drawn for (Blue)
static u32 g_logo_accent;          // accent the logo was last coloured for

static void logo_recolor(char *svg, u32 accent) {
    f32 bh, bs, bl, ah, as, al;
    rgb_to_hsl(LOGO_BASE_ACCENT, &bh, &bs, &bl);
    rgb_to_hsl(accent & 0xFFFFFF, &ah, &as, &al);
    f32 sscale = bs > 0 ? as / bs : 1;
    for (char *m = svg; (m = strchr(m, '#')) != NULL; m++) {
        if (!isxdigit((u8)m[1]) || !isxdigit((u8)m[6]) || isxdigit((u8)m[7])) continue;
        char hx[7];
        memcpy(hx, m + 1, 6);
        hx[6] = 0;
        u32 c = (u32)strtoul(hx, NULL, 16);
        if (c == 0xFFFFFF) continue; // the white chevron stays white
        f32 h, sat, l;
        rgb_to_hsl(c, &h, &sat, &l);
        char out[8];
        snprintf(out, sizeof out, "#%06X", (unsigned)hsl_to_rgb(h + (ah - bh), CLAMP(sat * sscale, 0, 1), l));
        memcpy(m, out, 7);
    }
}

static NSVGimage *icon_image(int id) {
    NSVGimage **slot;
    const char *nsrc = NULL;
    if (id >= ICON_NET_BASE) {
        int k = id - ICON_NET_BASE;
        if (k >= net_icon_count()) return NULL;
        if (g_net_img_n < net_icon_count()) {
            g_net_img = xrealloc(g_net_img, (size_t)net_icon_count() * sizeof *g_net_img);
            memset(g_net_img + g_net_img_n, 0, (size_t)(net_icon_count() - g_net_img_n) * sizeof *g_net_img);
            g_net_img_n = net_icon_count();
        }
        slot = &g_net_img[k];
        nsrc = net_icon_svg(k);
    } else if (id >= ICON_EXT_BASE) {
        int k = id - ICON_EXT_BASE;
        if (k >= g_next_img) return NULL;
        slot = &g_ext_img[k];
    } else slot = id == ICON_LOGO ? &g_logo_img : id == ICON_LOGO_SMALL ? &g_logo_small_img : id == ICON_BRANCH ? &g_branch_img : &g_icon_img[id];
    if (!*slot) {
        const char *src = nsrc ? nsrc : id == ICON_LOGO ? g_logo_svg : id == ICON_LOGO_SMALL ? g_logo_small_svg
                        : id == ICON_BRANCH ? g_branch_svg : icon_src(id);
        if (!src) return NULL;
        char *copy = strdup(src); // nsvgParse modifies its input
        if (id == ICON_LOGO || id == ICON_LOGO_SMALL) logo_recolor(copy, g_logo_accent = COL_ACCENT);
        for (char *m = copy; (m = strstr(m, ICON_THEME_MARK)) != NULL; m += 7) {
            char hex[8];
            snprintf(hex, sizeof hex, "#%06X", (unsigned)(COL_TEXT2 & 0xFFFFFF));
            memcpy(m, hex, 7);
        }
        for (char *m = copy; (m = strstr(m, ICON_THEME_SHADE)) != NULL; m += 7) {
            char hex[8];
            snprintf(hex, sizeof hex, "#%06X", (unsigned)(rgb_mix(COL_TEXT2, COL_BG, 0.55f) & 0xFFFFFF));
            memcpy(m, hex, 7);
        }
        *slot = nsvgParse(copy, "px", 96.0f);
        free(copy);
    }
    return *slot;
}

// RGBA pixels of icon id fitted (centred) into a w x h box; caller frees.
static u8 *icon_raster(int id, int w, int h) {
    NSVGimage *img = icon_image(id);
    if (!img || img->width <= 0 || img->height <= 0) return NULL;
    if (!g_rast) g_rast = nsvgCreateRasterizer();
    f32 sc = MIN((f32)w / img->width, (f32)h / img->height);
    u8 *buf = xcalloc((size_t)w * h, 4);
    nsvgRasterize(g_rast, img, (w - img->width * sc) * 0.5f, (h - img->height * sc) * 0.5f, sc, buf, w, h, w * 4);
    return buf;
}

typedef struct { int id, px; Glyph g; } IconSlot;
static IconSlot g_icon_cache[512];
// g_icon_cache_n lives in font.c (reset together with the atlas)

static Glyph *icon_glyph(int id, int px) {
    if (id < 0 || (id >= icon_id_limit() && (id < ICON_NET_BASE || id >= ICON_NET_BASE + net_icon_count())) || px <= 0 || px > 256) return NULL;
    for (int i = 0; i < g_icon_cache_n; i++)
        if (g_icon_cache[i].id == id && g_icon_cache[i].px == px) return &g_icon_cache[i].g;
    if (g_icon_cache_n >= (int)ARRAY_COUNT(g_icon_cache)) g_icon_cache_n = 0; // crude eviction (atlas keeps the pixels)
    u8 *buf = icon_raster(id, px, px);
    if (!buf) return NULL;
    int ax, ay;
    if (!atlas_pack(px, px, &ax, &ay)) { free(buf); return NULL; }
    for (int y = 0; y < px; y++) memcpy(&g_atlas[((size_t)(ay + y) * ATLAS_SIZE + ax) * 4], buf + (size_t)y * px * 4, (size_t)px * 4);
    free(buf);
    IconSlot *s = &g_icon_cache[g_icon_cache_n++];
    s->id = id;
    s->px = px;
    memset(&s->g, 0, sizeof s->g);
    s->g.x = (u16)ax;
    s->g.y = (u16)ay;
    s->g.w = (u16)px;
    s->g.h = (u16)px;
    return &s->g;
}

// Draw the icon for a file name at (x, y), s pixels. Returns false if it couldn't (caller falls back).
static bool draw_icon_for_name(f32 x, f32 y, f32 s, const char *name, bool exec) {
    Glyph *g = icon_glyph(icon_for_name(name, exec), (int)roundf(s));
    if (!g) return false;
    draw_glyph(g, roundf(x), roundf(y), (Color){1, 1, 1, 1});
    return true;
}

// A network location's icon (key as stored with the server); alpha < 1 for saved servers that aren't connected.
static bool draw_net_icon(f32 x, f32 y, f32 s, const char *key, f32 alpha) {
    Glyph *g = icon_glyph(ICON_NET_BASE + net_icon_find(key), (int)roundf(s));
    if (!g) return false;
    draw_glyph(g, roundf(x), roundf(y), (Color){1, 1, 1, alpha});
    return true;
}

// Large icons (grid view) get their own textures so they don't flood the glyph atlas.
typedef struct { int id, px; SDL_Texture *tex; u64 used; } BigIcon;
static BigIcon g_big_icons[96];
static int g_nbig;
static u64 g_big_clock;

static SDL_Texture *big_icon_tex(int id, int px) {
    if (id < 0 || id >= icon_id_limit() || px <= 0 || px > 512) return NULL;
    g_big_clock++;
    for (int i = 0; i < g_nbig; i++)
        if (g_big_icons[i].id == id && g_big_icons[i].px == px) {
            g_big_icons[i].used = g_big_clock;
            return g_big_icons[i].tex;
        }
    u8 *buf = icon_raster(id, px, px);
    if (!buf) return NULL;
    SDL_Texture *tex = SDL_CreateTexture(g_ren, SDL_PIXELFORMAT_RGBA32, SDL_TEXTUREACCESS_STATIC, px, px);
    if (tex) {
        SDL_UpdateTexture(tex, NULL, buf, px * 4);
        SDL_SetTextureBlendMode(tex, SDL_BLENDMODE_BLEND);
        SDL_SetTextureScaleMode(tex, SDL_SCALEMODE_LINEAR);
    }
    free(buf);
    if (!tex) return NULL;
    int k = g_nbig;
    if (g_nbig == (int)ARRAY_COUNT(g_big_icons)) { // evict least recently used
        k = 0;
        for (int i = 1; i < g_nbig; i++)
            if (g_big_icons[i].used < g_big_icons[k].used) k = i;
        SDL_DestroyTexture(g_big_icons[k].tex);
    } else {
        g_nbig++;
    }
    g_big_icons[k] = (BigIcon){id, px, tex, g_big_clock};
    return tex;
}

// Theme changed: icons using the theme colour mark are parsed and rasterized again.
static bool g_logo_changed; // the window icon should be rebuilt (app.c)

static void icons_sync_theme(void) {
    if ((g_logo_img || g_logo_small_img) && g_logo_accent != COL_ACCENT) { // accent changed: recolour the logo
        if (g_logo_img) nsvgDelete(g_logo_img);
        if (g_logo_small_img) nsvgDelete(g_logo_small_img);
        g_logo_img = g_logo_small_img = NULL;
        g_logo_accent = COL_ACCENT;
        g_logo_changed = true;
        atlas_reset();
    }
    if (g_icon_main == COL_TEXT2 && g_icon_bg == COL_BG) return;
    bool first = g_icon_main == 0xFFFFFFFF;
    g_icon_main = COL_TEXT2;
    g_icon_bg = COL_BG;
    if (first) return;
    bool any = false;
    for (int i = 0; i < ICON_COUNT; i++)
        if (g_icon_img[i] && (strstr(icon_src(i), ICON_THEME_MARK) || strstr(icon_src(i), ICON_THEME_SHADE))) {
            nsvgDelete(g_icon_img[i]);
            g_icon_img[i] = NULL;
            any = true;
        }
    for (int i = 0; i < g_net_img_n; i++)
        if (g_net_img[i] && (strstr(net_icon_svg(i), ICON_THEME_MARK) || strstr(net_icon_svg(i), ICON_THEME_SHADE))) {
            nsvgDelete(g_net_img[i]);
            g_net_img[i] = NULL;
            any = true;
        }
    if (!any) return;
    for (int i = 0; i < g_nbig; i++) SDL_DestroyTexture(g_big_icons[i].tex);
    g_nbig = 0;
    atlas_reset();
}

static int icon_theme_find(const char *name) {
    for (int i = 0; i < icon_theme_count(); i++)
        if (str_ieq(name, icon_theme_name(i))) return i;
    return -1;
}

// Drop parsed SVGs and every rasterized copy (theme switched or reloaded).
static void icons_flush(void) {
    for (int i = 0; i < ICON_COUNT; i++) {
        if (g_icon_img[i]) nsvgDelete(g_icon_img[i]);
        g_icon_img[i] = NULL;
    }
    for (int i = 0; i < g_next_img; i++)
        if (g_ext_img[i]) nsvgDelete(g_ext_img[i]);
    free(g_ext_img);
    CustomIconTheme *c = icon_custom();
    g_next_img = c ? c->next : 0;
    g_ext_img = g_next_img ? xcalloc((size_t)g_next_img, sizeof(NSVGimage *)) : NULL;
    for (int i = 0; i < g_nbig; i++) SDL_DestroyTexture(g_big_icons[i].tex);
    g_nbig = 0;
    atlas_reset(); // glyph-atlas icons (and text, re-rasterized on demand)
}

static void icon_set_theme(int t) {
    if (t < 0 || t >= icon_theme_count() || t == g_icon_theme) return;
    g_icon_theme = t;
    icons_flush();
}

static char *icon_read_svg(const char *path) {
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    char *buf = xmalloc(512 * 1024 + 1);
    size_t n = fread(buf, 1, 512 * 1024, f);
    fclose(f);
    buf[n] = 0;
    if (!n || !strstr(buf, "<svg")) { free(buf); return NULL; }
    return buf;
}

static void icon_custom_free(CustomIconTheme *c) {
    for (int i = 0; i < ICON_COUNT; i++) free(c->svg[i]);
    for (int k = 0; k < c->next; k++) free(c->ext_svg[k]);
    free(c->ext);
    free(c->ext_svg);
    memset(c, 0, sizeof *c);
}

static int cmp_cit(const void *a, const void *b) { return natcmp(((const CustomIconTheme *)a)->name, ((const CustomIconTheme *)b)->name); }

// (Re)load the custom icon themes from dir; keeps the current theme selected by name.
static void icon_themes_scan(const char *dir) {
    char cur[64];
    snprintf(cur, sizeof cur, "%s", icon_theme_name(g_icon_theme));
    bool was_custom = g_icon_theme >= ICON_THEMES;
    for (int i = 0; i < g_ncit; i++) icon_custom_free(&g_cit[i]);
    g_ncit = 0;
    for (int i = 0; i < g_nnet_custom; i++) free(g_net_custom[i].svg);
    free(g_net_custom);
    g_net_custom = NULL;
    g_nnet_custom = 0;
    net_icons_free_images();
    atlas_reset(); // (network icon ids may now point at other icons)
    DIR *d = opendir(dir);
    struct dirent *de;
    while (d && (de = readdir(d)) != NULL && g_ncit < MAX_CUSTOM_ICON_THEMES) {
        if (de->d_name[0] == '.' || strlen(de->d_name) >= 64) continue;
        char tdir[PATH_MAX];
        snprintf(tdir, sizeof tdir, "%s/%s", dir, de->d_name);
        struct stat st;
        if (stat(tdir, &st) != 0 || !S_ISDIR(st.st_mode)) continue;
        bool clash = false; // a built-in name can't be reused
        for (int i = 0; i < ICON_THEMES; i++) clash |= str_ieq(de->d_name, g_icon_theme_names[i]);
        if (clash) continue;
        CustomIconTheme *c = &g_cit[g_ncit];
        memset(c, 0, sizeof *c);
        snprintf(c->name, sizeof c->name, "%s", de->d_name);
        char path[PATH_MAX + 80], line[256];
        snprintf(path, sizeof path, "%s/theme.conf", tdir);
        FILE *cf = fopen(path, "r");
        while (cf && fgets(line, sizeof line, cf)) {
            line[strcspn(line, "\r\n")] = 0;
            if (!strncmp(line, "base=", 5)) for (int i = 0; i < ICON_THEMES; i++) if (str_ieq(line + 5, g_icon_theme_names[i])) c->base = i;
        }
        if (cf) fclose(cf);
        int found = 0;
        DIR *td = opendir(tdir);
        struct dirent *fe;
        while (td && (fe = readdir(td)) != NULL) {
            size_t l = strlen(fe->d_name);
            if (l < 5 || strcasecmp(fe->d_name + l - 4, ".svg")) continue;
            char nm[NAME_MAX + 1];
            snprintf(nm, sizeof nm, "%.*s", (int)(l - 4), fe->d_name);
            for (char *q = nm; *q; q++) *q = (char)tolower((u8)*q);
            snprintf(path, sizeof path, "%s/%s", tdir, fe->d_name);
            if (!strncmp(nm, "net-", 4) && nm[4] && strlen(nm + 4) < 64) { // a network location icon
                char *svg = icon_read_svg(path);
                if (!svg) continue;
                g_net_custom = xrealloc(g_net_custom, (size_t)(g_nnet_custom + 1) * sizeof *g_net_custom);
                NetIconCustom *ni = &g_net_custom[g_nnet_custom++];
                snprintf(ni->key, sizeof ni->key, "custom/%s/%s", c->name, nm + 4);
                snprintf(ni->theme, sizeof ni->theme, "%s", c->name);
                snprintf(ni->label, sizeof ni->label, "%s", nm + 4); // "my-vm" -> "My vm"
                for (char *q = ni->label; *q; q++) if (*q == '-' || *q == '_') *q = ' ';
                ni->label[0] = (char)toupper((u8)ni->label[0]);
                ni->svg = svg;
                continue; // (doesn't make the folder a file icon theme)
            }
            if (!strncmp(nm, "ext-", 4) && nm[4] && strlen(nm + 4) < 32) {
                char *svg = icon_read_svg(path);
                if (!svg) continue;
                c->ext = xrealloc(c->ext, (size_t)(c->next + 1) * sizeof *c->ext);
                c->ext_svg = xrealloc(c->ext_svg, (size_t)(c->next + 1) * sizeof(char *));
                snprintf(c->ext[c->next], sizeof c->ext[0], "%s", nm + 4);
                c->ext_svg[c->next++] = svg;
                found++;
            } else {
                int id = icon_find(nm);
                if (id < 0 || c->svg[id]) continue;
                if ((c->svg[id] = icon_read_svg(path)) != NULL) found++;
            }
        }
        if (td) closedir(td);
        if (found) g_ncit++;
        else icon_custom_free(c);
    }
    if (d) closedir(d);
    qsort(g_cit, (size_t)g_ncit, sizeof g_cit[0], cmp_cit);
    int t = icon_theme_find(cur);
    g_icon_theme = t >= 0 ? t : 0;
    if (was_custom || g_icon_theme >= ICON_THEMES) icons_flush(); // its files may have changed
}

