static int icon_find(const char *name) {
    int lo = 0, hi = ICON_COUNT - 1; // table is sorted by name
    while (lo <= hi) {
        int mid = (lo + hi) / 2, c = strcmp(name, g_icon_names[mid]);
        if (!c) return mid;
        if (c < 0) hi = mid - 1;
        else lo = mid + 1;
    }
    return -1;
}

