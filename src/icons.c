// Icon index for a file name (no folders). exec: has the executable bit.
static int icon_for_name(const char *name, bool exec) {
    static int cache_default = -2, cache_exec = -2;
    if (cache_default == -2) {
        cache_default = icon_find("document");
        cache_exec = icon_find("console");
    }
    char low[NAME_MAX + 1];
    size_t n = 0;
    for (; name[n] && n < NAME_MAX; n++) low[n] = (char)ascii_lower((u8)name[n]);
    low[n] = 0;
    CustomIconTheme *ct = icon_custom();
    if (ct && ct->next) {
        const char *d = strrchr(low, '.');
        if (d && d != low)
            for (int k = 0; k < ct->next; k++)
                if (!strcmp(d + 1, ct->ext[k])) return ICON_EXT_BASE + k;
    }
    for (size_t i = 0; i < ARRAY_COUNT(g_icon_filenames); i++)
        if (!strcmp(low, g_icon_filenames[i].key)) return icon_find(g_icon_filenames[i].icon);
    for (size_t i = 0; i < ARRAY_COUNT(g_icon_prefixes); i++)
        if (!strncmp(low, g_icon_prefixes[i].key, strlen(g_icon_prefixes[i].key))) return icon_find(g_icon_prefixes[i].icon);
    // double extensions first (e.g. ".d.ts", ".tar.gz" are fine with the last part)
    const char *dot = strrchr(low, '.');
    if (dot && dot != low) {
        if (!strcmp(dot, ".ts") && n > 5 && !strcmp(low + n - 5, ".d.ts")) return icon_find("typescript");
        for (size_t i = 0; i < ARRAY_COUNT(g_icon_exts); i++)
            if (!strcmp(dot + 1, g_icon_exts[i].key)) return icon_find(g_icon_exts[i].icon);
    }
    return exec ? cache_exec : cache_default;
}

// Folder icon of the current set for a folder name: special folders (src, .git, Documents...) get their own.
static int folder_icon_for_name(const char *name) {
    while (*name == '.' || *name == '_') name++;
    char low[64];
    size_t n = 0;
    for (; name[n] && n + 1 < sizeof low; n++) low[n] = (char)tolower((unsigned char)name[n]);
    low[n] = 0;
    int lo = 0, hi = (int)ARRAY_COUNT(g_folder_icon_names) - 1;
    while (n && !name[n] && lo <= hi) {
        int mid = (lo + hi) / 2, c = strcmp(low, g_folder_icon_names[mid].name);
        if (!c) {
            int id = icon_find(g_folder_icon_names[mid].icon);
            if (id >= 0) return id;
            break;
        }
        if (c < 0) hi = mid - 1;
        else lo = mid + 1;
    }
    return icon_find("folder");
}

