static int net_icon_count(void) { return NET_ICON_BUILTIN + g_nnet_custom; }
static const char *net_icon_key(int i) { return i < NET_ICON_BUILTIN ? g_net_icons[i].key : g_net_custom[i - NET_ICON_BUILTIN].key; }
static const char *net_icon_label(int i) { return i < NET_ICON_BUILTIN ? g_net_icons[i].label : g_net_custom[i - NET_ICON_BUILTIN].label; }
static const char *net_icon_svg(int i) { return i < NET_ICON_BUILTIN ? g_net_icons[i].svg : g_net_custom[i - NET_ICON_BUILTIN].svg; }
// Index of the icon with this key; the default (globe) for "" or a key that no longer exists (a removed custom icon).
static int net_icon_find(const char *key) {
    if (key && key[0])
        for (int i = 0; i < net_icon_count(); i++)
            if (!strcmp(net_icon_key(i), key)) return i;
    return 0;
}
static void net_icons_free_images(void) {
    for (int i = 0; i < g_net_img_n; i++)
        if (g_net_img[i]) nsvgDelete(g_net_img[i]);
    free(g_net_img);
    g_net_img = NULL;
    g_net_img_n = 0;
}

